/// Complete atomic input for one fenced Lease heartbeat.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct RenewLease {
  /// Stable identity used to replay an identical heartbeat.
  pub idempotency_key: crate::IdempotencyKey,
  /// Current fenced Lease authority.
  pub lease: LeaseAccess,
  /// Job identity echoed by the Agent's Lease assignment.
  pub job_id: JobId,
  /// Attempt number echoed by the Agent's Lease assignment.
  pub attempt: AttemptNumber,
  /// Authoritative time at which the heartbeat was accepted.
  pub observed_at: Timestamp,
  /// New exclusive Lease deadline when renewal is allowed.
  pub expires_at: Timestamp,
}

impl RenewLease {
  /// Revalidates the proposed renewal window at an adapter seam.
  pub fn validate(&self) -> Result<(), StoreError> {
    if self.expires_at <= self.observed_at {
      return Err(StoreError::invalid(
        StoreOperation::RenewLease,
        StoreInputError::InvalidLeaseWindow,
      ));
    }
    Ok(())
  }
}

/// Authoritative control decision returned by one Lease heartbeat.
#[derive(Clone, Copy, Debug, Eq, PartialEq, serde::Deserialize, serde::Serialize)]
pub enum LeaseHeartbeatOutcome {
  /// Continue execution under the renewed deadline.
  Continue {
    /// Exclusive renewed Lease deadline.
    expires_at: Timestamp,
  },
  /// Cooperatively cancel the current Job.
  Cancel,
  /// Stop immediately because Lease ownership is no longer current.
  Fenced,
  /// Finish current work under the renewed deadline and accept no more work.
  Drain {
    /// Exclusive renewed Lease deadline.
    expires_at: Timestamp,
  },
}

/// One immutable ordered Job event and its exact payload identity.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct DurableJobEvent {
  /// Positive sequence within one Job stream.
  sequence: EventSequence,
  /// Stable provider-neutral event classification.
  kind: JobEventKind,
  /// Source-observed time retained independently of persistence time.
  occurred_at: Timestamp,
  /// Bounded validated event payload.
  payload: Value,
  /// Digest of the canonical event kind, time, and bounded payload.
  digest: EventDigest,
}

impl DurableJobEvent {
  /// Validates the payload and computes its canonical event digest.
  pub fn new(
    sequence: EventSequence,
    kind: JobEventKind,
    occurred_at: Timestamp,
    payload: Value,
  ) -> Result<Self, StoreInputError> {
    require_bounded_json(
      &payload,
      MAX_JOB_EVENT_PAYLOAD_BYTES,
      StoreInputError::EventPayloadTooLarge,
    )?;
    let canonical_payload = canonicalize_json(payload).map_err(|_| StoreInputError::JsonDocumentTooDeep)?;
    let encoded = serde_json::to_vec(&(kind.as_str(), occurred_at.unix_millis(), &canonical_payload))
      .map_err(|_| StoreInputError::EventPayloadTooLarge)?;
    let digest = EventDigest::from_bytes(Sha256::digest(encoded).into());
    Ok(Self {
      sequence,
      kind,
      occurred_at,
      payload: canonical_payload,
      digest,
    })
  }

  /// Returns the positive sequence within the Job stream.
  #[must_use]
  pub const fn sequence(&self) -> EventSequence {
    self.sequence
  }

  /// Returns the stable provider-neutral event classification.
  #[must_use]
  pub const fn kind(&self) -> &JobEventKind {
    &self.kind
  }

  /// Returns the source-observed event time.
  #[must_use]
  pub const fn occurred_at(&self) -> Timestamp {
    self.occurred_at
  }

  /// Borrows the validated canonical payload.
  #[must_use]
  pub const fn payload(&self) -> &Value {
    &self.payload
  }

  /// Returns the digest computed from the complete canonical event content.
  #[must_use]
  pub const fn digest(&self) -> EventDigest {
    self.digest
  }
}

/// Complete atomic input for one contiguous idempotent Job-event append.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct AppendJobEvents {
  /// Current fenced ownership.
  pub lease: LeaseAccess,
  /// Contiguous batch, which may include an already durable replay prefix.
  pub events: Vec<DurableJobEvent>,
  /// Verified immutable chunks covering only newly accepted stdout/stderr events.
  pub log_chunks: Vec<LogChunkManifest>,
  /// Authoritative acceptance time used to reject expired Lease ownership.
  pub accepted_at: Timestamp,
}

impl AppendJobEvents {
  /// Validates sequence continuity within one batch.
  pub fn new(lease: LeaseAccess, events: Vec<DurableJobEvent>, accepted_at: Timestamp) -> Result<Self, StoreError> {
    let request = Self {
      lease,
      events,
      log_chunks: Vec::new(),
      accepted_at,
    };
    request.validate()?;
    Ok(request)
  }

  /// Attaches verified chunk manifests prepared after reading the durable cursor.
  pub fn with_log_chunks(mut self, log_chunks: Vec<LogChunkManifest>) -> Result<Self, StoreError> {
    self.log_chunks = log_chunks;
    self.validate()?;
    Ok(self)
  }

  /// Revalidates the batch bound and sequence continuity at an adapter seam.
  pub fn validate(&self) -> Result<(), StoreError> {
    let events = &self.events;
    if events.is_empty() {
      return Err(StoreError::invalid(
        StoreOperation::AppendJobEvents,
        StoreInputError::EmptyEventBatch,
      ));
    }
    if events.len() > MAX_JOB_EVENT_BATCH_SIZE {
      return Err(StoreError::invalid(
        StoreOperation::AppendJobEvents,
        StoreInputError::EventBatchTooLarge,
      ));
    }
    if events
      .iter()
      .try_fold(0_usize, |total, event| {
        serde_json::to_vec(&(
          event.sequence().get(),
          event.kind().as_str(),
          event.occurred_at().unix_millis(),
          event.payload(),
        ))
        .ok()
        .and_then(|encoded| total.checked_add(encoded.len()))
      })
      .is_none_or(|bytes| bytes > MAX_JOB_EVENT_BATCH_BYTES)
    {
      return Err(StoreError::invalid(
        StoreOperation::AppendJobEvents,
        StoreInputError::RequestTooLarge,
      ));
    }
    if events
      .windows(2)
      .any(|pair| pair[0].sequence().get().checked_add(1) != Some(pair[1].sequence().get()))
    {
      return Err(StoreError::invalid(
        StoreOperation::AppendJobEvents,
        StoreInputError::NonContiguousEventBatch,
      ));
    }
    let first_sequence = events[0].sequence().get();
    let last_sequence = events[events.len() - 1].sequence().get();
    let mut ranges: Vec<_> = self
      .log_chunks
      .iter()
      .map(|chunk| (chunk.first_sequence(), chunk.last_sequence()))
      .collect();
    ranges.sort_unstable();
    if ranges
      .iter()
      .any(|(first, last)| *first < first_sequence || *last > last_sequence || *first == 0 || *last < *first)
      || ranges.windows(2).any(|pair| pair[0].1 >= pair[1].0)
    {
      return Err(StoreError::invalid(
        StoreOperation::AppendJobEvents,
        StoreInputError::InvalidLogChunkManifest,
      ));
    }
    Ok(())
  }
}

/// Cursor observed before writing immutable log objects.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct JobEventAppendPreparation {
  /// Greatest contiguous event sequence already durable, or zero.
  pub durable_through: u64,
}

/// Validates that manifests cover every newly accepted log event exactly once.
pub fn validate_new_log_chunks(
  events: &[DurableJobEvent],
  durable_through: u64,
  chunks: &[LogChunkManifest],
) -> Result<(), StoreError> {
  let expected: Vec<_> = events
    .iter()
    .filter(|event| event.sequence().get() > durable_through)
    .filter_map(|event| match event.kind().as_str() {
      "stdout" => Some((event.sequence().get(), BuildLogStream::Stdout)),
      "stderr" => Some((event.sequence().get(), BuildLogStream::Stderr)),
      _ => None,
    })
    .collect();
  let mut covered = Vec::new();
  for chunk in chunks {
    if chunk.first_sequence() <= durable_through {
      return invalid_log_chunks();
    }
    for sequence in chunk.first_sequence()..=chunk.last_sequence() {
      covered.push((sequence, chunk.stream()));
    }
  }
  covered.sort_unstable();
  let mut expected = expected;
  expected.sort_unstable();
  if covered != expected {
    return invalid_log_chunks();
  }
  Ok(())
}

fn invalid_log_chunks<T>() -> Result<T, StoreError> {
  Err(StoreError::invalid(
    StoreOperation::AppendJobEvents,
    StoreInputError::InvalidLogChunkManifest,
  ))
}

