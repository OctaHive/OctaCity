/// Complete atomic input for compatible ready-Job selection and Lease creation.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct JobClaim {
  /// New opaque Lease identity generated by the caller.
  pub lease_id: LeaseId,
  /// Secret opaque fence generated independently of the Lease identity.
  pub fence: LeaseFence,
  /// Accepting Agent identity.
  pub agent_id: AgentId,
  /// Current Agent process registration.
  pub registration_epoch: RegistrationEpoch,
  /// Pool to which the current Agent registration belongs.
  pub pool_id: PoolId,
  /// Current Agent capacity and backend health used for compatibility.
  pub snapshot: HostSnapshot,
  /// Authoritative claim time.
  pub claimed_at: Timestamp,
  /// Initial Lease expiry.
  pub expires_at: Timestamp,
}

/// Validated authoritative time window for a newly created Lease.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct LeaseWindow {
  /// Time at which ownership begins.
  pub claimed_at: Timestamp,
  /// Initial ownership deadline.
  pub expires_at: Timestamp,
}

impl LeaseWindow {
  /// Creates a positive Lease window.
  pub fn new(claimed_at: Timestamp, expires_at: Timestamp) -> Result<Self, StoreError> {
    let window = Self { claimed_at, expires_at };
    window.validate()?;
    Ok(window)
  }

  fn validate(self) -> Result<(), StoreError> {
    if self.expires_at <= self.claimed_at {
      return Err(StoreError::invalid(
        StoreOperation::ClaimReadyJob,
        StoreInputError::InvalidLeaseWindow,
      ));
    }
    Ok(())
  }
}

impl JobClaim {
  /// Validates one bounded Lease window.
  pub fn new(
    lease_id: LeaseId,
    fence: LeaseFence,
    agent_id: AgentId,
    registration_epoch: RegistrationEpoch,
    pool_id: PoolId,
    snapshot: HostSnapshot,
    window: LeaseWindow,
  ) -> Result<Self, StoreError> {
    let request = Self {
      lease_id,
      fence,
      agent_id,
      registration_epoch,
      pool_id,
      snapshot,
      claimed_at: window.claimed_at,
      expires_at: window.expires_at,
    };
    request.validate()?;
    Ok(request)
  }

  /// Revalidates the Lease window at an adapter seam.
  pub fn validate(&self) -> Result<(), StoreError> {
    LeaseWindow {
      claimed_at: self.claimed_at,
      expires_at: self.expires_at,
    }
    .validate()
  }
}

