/// Maximum UTF-8 bytes in one extensible operating-system or architecture label.
pub const MAX_AGENT_PLATFORM_LABEL_BYTES: usize = 64;
/// Maximum encoded bytes in one scheduler-visible Agent inventory document.
pub const MAX_AGENT_INVENTORY_BYTES: usize = 256 * 1_024;

/// A high-entropy bearer credential whose formatting never reveals its bytes.
///
/// Callers must construct the 32 bytes with a cryptographically secure random
/// generator. The store persists only [`CredentialDigest`].
#[derive(Clone)]
pub struct CredentialSecret(Zeroizing<[u8; 32]>);

impl CredentialSecret {
  /// Wraps 256 bits generated by a cryptographically secure random source.
  #[must_use]
  pub fn from_bytes(bytes: [u8; 32]) -> Self {
    Self(Zeroizing::new(bytes))
  }

  /// Derives the irreversible, domain-separated value stored by adapters.
  #[must_use]
  pub fn digest(&self) -> CredentialDigest {
    let mut hash = Sha256::new();
    hash.update(b"octacity.agent-credential.v1\0");
    hash.update(self.0.as_slice());
    CredentialDigest(hash.finalize().into())
  }
}

impl fmt::Debug for CredentialSecret {
  fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
    formatter.write_str("CredentialSecret([REDACTED])")
  }
}

impl fmt::Display for CredentialSecret {
  fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
    formatter.write_str("[REDACTED]")
  }
}

impl PartialEq for CredentialSecret {
  fn eq(&self, other: &Self) -> bool {
    self.digest().matches(other.digest())
  }
}

impl Eq for CredentialSecret {}

/// Fixed-size irreversible verifier for an Agent bearer credential.
#[derive(Clone, Copy, Eq, Hash, PartialEq)]
pub struct CredentialDigest([u8; 32]);

impl CredentialDigest {
  /// Constructs a digest loaded from trusted durable state.
  #[must_use]
  pub const fn from_bytes(bytes: [u8; 32]) -> Self {
    Self(bytes)
  }

  /// Returns bytes suitable for persistence, never the original credential.
  #[must_use]
  pub const fn as_bytes(self) -> [u8; 32] {
    self.0
  }

  /// Compares two digests without data-dependent early exit.
  #[must_use]
  pub fn matches(self, other: Self) -> bool {
    let difference = self
      .0
      .iter()
      .zip(other.0)
      .fold(0_u8, |difference, (left, right)| difference | (*left ^ right));
    difference == 0
  }
}

impl fmt::Debug for CredentialDigest {
  fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
    formatter.write_str("CredentialDigest([REDACTED])")
  }
}

/// Provider-neutral Agent host platform used by enrollment admission policy.
#[derive(Clone, Debug, Deserialize, Eq, Hash, Ord, PartialEq, PartialOrd, Serialize)]
pub struct AgentPlatform {
  operating_system: String,
  architecture: String,
}

impl AgentPlatform {
  /// Constructs an extensible canonical platform from bounded lowercase labels.
  pub fn new(operating_system: impl Into<String>, architecture: impl Into<String>) -> Result<Self, StoreInputError> {
    let operating_system = operating_system.into();
    let architecture = architecture.into();
    if !valid_platform_label(&operating_system) || !valid_platform_label(&architecture) {
      return Err(StoreInputError::InvalidAgentPlatform);
    }
    Ok(Self {
      operating_system,
      architecture,
    })
  }

  /// Returns the canonical operating-system label.
  #[must_use]
  pub fn operating_system(&self) -> &str {
    &self.operating_system
  }

  /// Returns the canonical architecture label.
  #[must_use]
  pub fn architecture(&self) -> &str {
    &self.architecture
  }
}

/// Platform restriction carried by one enrollment credential.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(rename_all = "snake_case", tag = "policy", content = "platform")]
pub enum ExpectedAgentPlatform {
  /// Any syntactically valid Agent platform may consume the credential.
  Any,
  /// Only one exact operating-system and architecture pair may consume it.
  Exact(AgentPlatform),
}

impl ExpectedAgentPlatform {
  /// Reports whether a presented platform satisfies this policy.
  #[must_use]
  pub fn accepts(&self, actual: &AgentPlatform) -> bool {
    match self {
      Self::Any => true,
      Self::Exact(expected) => expected == actual,
    }
  }
}

/// Complete atomic request to issue one single-use enrollment credential.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct IssueAgentEnrollment {
  /// Stable credential and idempotency identity.
  pub credential_id: EnrollmentCredentialId,
  /// Plaintext returned by the trusted caller and never persisted.
  pub credential: CredentialSecret,
  /// Agent Pool to which successful enrollment binds the Agent.
  pub pool_id: PoolId,
  /// Immutable Pool policy version captured when the credential is issued.
  pub pool_version: PoolVersion,
  /// Platform admission policy checked when the credential is consumed.
  pub expected_platform: ExpectedAgentPlatform,
  /// Authoritative issue time.
  pub issued_at: Timestamp,
  /// Exclusive credential expiry.
  pub expires_at: Timestamp,
}

impl IssueAgentEnrollment {
  /// Validates a bounded credential lifetime.
  pub fn new(
    credential_id: EnrollmentCredentialId,
    credential: CredentialSecret,
    pool_id: PoolId,
    pool_version: PoolVersion,
    expected_platform: ExpectedAgentPlatform,
    issued_at: Timestamp,
    expires_at: Timestamp,
  ) -> Result<Self, StoreError> {
    let request = Self {
      credential_id,
      credential,
      pool_id,
      pool_version,
      expected_platform,
      issued_at,
      expires_at,
    };
    request.validate()?;
    Ok(request)
  }

  /// Revalidates invariants after construction of this mutable request value.
  pub fn validate(&self) -> Result<(), StoreError> {
    require_credential_window(StoreOperation::IssueAgentEnrollment, self.issued_at, self.expires_at)
  }
}

/// Durable result of issuing an enrollment credential.
#[derive(Clone, Debug, Eq, PartialEq)]
