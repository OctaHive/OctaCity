/// Enrollment or registration identity selected for explicit revocation.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum AgentCredentialTarget {
  /// Revoke an unused enrollment credential.
  Enrollment(EnrollmentCredentialId),
  /// Revoke an Agent registration credential.
  Registration(RegistrationCredentialId),
}

/// Idempotent explicit Agent credential revocation.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct RevokeAgentCredential {
  /// Credential selected for revocation.
  pub target: AgentCredentialTarget,
  /// Authoritative revocation time.
  pub revoked_at: Timestamp,
}

fn require_credential_window(
  operation: StoreOperation,
  issued_at: Timestamp,
  expires_at: Timestamp,
) -> Result<(), StoreError> {
  if expires_at <= issued_at {
    return Err(StoreError::invalid(operation, StoreInputError::InvalidCredentialWindow));
  }
  Ok(())
}

fn valid_platform_label(value: &str) -> bool {
  !value.is_empty()
    && value.len() <= MAX_AGENT_PLATFORM_LABEL_BYTES
    && value
      .bytes()
      .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || matches!(byte, b'-' | b'_' | b'.'))
}
